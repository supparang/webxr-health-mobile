export function detectQuizTopic(prompt){
 if(/คณิต|บวก|ลบ|คูณ|หาร|ตัวเลข/.test(prompt))return "math";
 if(/วิทยา|พืช|สัตว์|โลก|ธรรมชาติ/.test(prompt))return "science";
 return "general";
}
export function getQuizQuestions(topic,ageLevel,count=5){
 const source=BANK[Object.hasOwn(BANK,topic)?topic:"general"];
 const n=Math.max(1,Math.min(source.length,Number.isFinite(count)?Math.floor(count):5));
 // Older students see more questions; age does not change the verified answer key.
 const offset={p1:0,p4:1,m1:2,m4:3}[ageLevel]??0;
 return Array.from({length:n},(_,i)=>source[(i+offset)%source.length]).map(item=>({...item,a:[...item.a]}));
}
